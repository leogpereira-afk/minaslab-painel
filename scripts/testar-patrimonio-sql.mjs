// PGLITE_ENTRY aponta para uma instalação isolada de @electric-sql/pglite.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {PGlite}=await import(pathToFileURL(process.env.PGLITE_ENTRY).href);
const db=new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role;
create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);`);
await db.exec(await readFile(new URL('../supabase/migrations/20260920_ml_patrimonio.sql',import.meta.url),'utf8'));
let checks=0;
const call=async(action,tipo,id,dados={})=>(await db.query('select public.ml_patrimonio_gravar($1,$2,$3,$4,$5) as valor',[action,tipo,id,JSON.stringify(dados),'teste'])).rows[0].valor;
await call('salvar','setor','lab',{sigla:'LAB',nome:'Laboratório'});
const bem={setorSigla:'LAB',nomeGenerico:'Balança',situacao:'uso',valor:3000,dataAquisicao:'2025-01-01'};
let mapa=await call('salvar','bem','b1',bem);const codigo=mapa.b1.codigo;
assert.match(codigo,/^ML-LAB-\d{6}$/);checks++;
mapa=await call('salvar','bem','b1',{...bem,codigo:'ADULTERADO',valor:5000});assert.equal(mapa.b1.codigo,codigo);checks++;
await Promise.all(Array.from({length:12},(_,i)=>call('salvar','bem',`c${i}`,bem)));
const codigos=(await db.query("select dados->>'codigo' as codigo from public.ml_patrimonio where tipo='bem'")).rows.map(x=>x.codigo);
assert.equal(new Set(codigos).size,13);checks++;
await assert.rejects(call('remover','setor','lab'),/possui bens/);checks++;
await assert.rejects(call('salvar','setor','lab',{sigla:'ALT',nome:'Outro'}),/não pode mudar/);checks++;
await assert.rejects(call('salvar','bem','futuro',{...bem,dataAquisicao:'2999-01-01'}),/futura/);checks++;
await assert.rejects(call('salvar','bem','negativo',{...bem,valor:-1}),/Valor inválido/);checks++;
await assert.rejects(call('salvar','bem','semsetor',{...bem,setorSigla:'ZZ'}),/setor cadastrado/);checks++;
await assert.rejects(call('salvar','setor','duplicado',{sigla:'LAB',nome:'Duplicado'}),/duplicate key/);checks++;
mapa=await call('salvar','bem','b1',{...bem,situacao:'baixado'});assert.equal(mapa.b1.situacao,'baixado');checks++;
await call('remover','bem','b1');assert.equal((await db.query("select apagado from public.ml_patrimonio where id='b1'")).rows[0].apagado,true);checks++;
await assert.rejects(call('salvar','bem','b1',bem),/removido/);checks++;
const setor=await call('iniciar','setor','lab',{sigla:'LAB',nome:'Não sobrescrever'});assert.equal(setor.lab.nome,'Laboratório');checks++;
await assert.rejects(call('salvar','foto','foto1',{bemId:'inexistente'}),/Bem não encontrado/);checks++;
await db.exec('set role anon');await assert.rejects(db.query('select * from public.ml_patrimonio'),/permission denied/);await assert.rejects(call('salvar','bem','indevido',bem),/permission denied/);checks+=2;
console.log(`${checks} verificações PostgreSQL passaram (banco isolado, sem produção).`);
await db.close();
